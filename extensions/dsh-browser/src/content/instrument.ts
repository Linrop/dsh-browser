/**
 * MAIN-world page hooks used when `chrome.debugger` is unavailable.
 *
 * The exported installer is serialized into the page by
 * `chrome.scripting.executeScript({ world: 'MAIN', func })`, so its body must
 * stay self-contained: it may only use its own locals and page globals. That
 * is why the message marker, flag, and text cap are repeated inside the
 * function instead of referring to module constants.
 *
 * The hook must never change page behavior: every wrapper rethrows the
 * original outcome, and every reporting path swallows its own failures.
 *
 * Instrument data is page-controlled content. The channel below only keeps
 * ordinary look-alike messages out of the telemetry buffer; it is not a trust
 * boundary, and every consumer must treat the entry payload as untrusted
 * (the background wraps console and network output in nonce-delimited
 * untrusted-content blocks).
 *
 * @module
 */

/** Marker a page-side entry carries inside its channel event. */
export const INSTRUMENT_MESSAGE_MARKER = '__dshBrowserInstrument'

/** Global flag making repeated injection idempotent. */
export const INSTRUMENT_GLOBAL_FLAG = '__dshBrowserInstrumentInstalled'

/** Longest text a hook sends in one entry. */
export const MAX_INSTRUMENT_TEXT = 16_384

/** One console line or page exception observed by the fallback hook. */
export interface InstrumentConsoleEntry {
  kind: 'console'
  type: string
  text: string
  url: string
  line?: number
  column?: number
  timestamp: number
}

/** One fetch/XHR call observed by the fallback hook. */
export interface InstrumentNetworkEntry {
  kind: 'network'
  url: string
  method: string
  status: number
  errorText?: string
  timestamp: number
}

/** Any entry the fallback hook posts to the content script. */
export type InstrumentEntry = InstrumentConsoleEntry | InstrumentNetworkEntry

/** Message envelope posted from the MAIN world to the content script. */
export interface InstrumentMessage {
  [INSTRUMENT_MESSAGE_MARKER]: true
  entry: InstrumentEntry
}

/**
 * Install the console and network hooks in the current MAIN world.
 *
 * Idempotent: a second injection on the same document returns immediately.
 * Network hooks cover `fetch` and `XMLHttpRequest`; document and resource
 * requests are the documented gap.
 *
 * The hook receives its channel name through the injection arguments and
 * keeps it in this closure. It never puts the channel in the envelope, so a
 * page that only listens on `message` or reads posted data cannot recover the
 * name from an entry.
 * @param channel - one-time random channel name generated by the background.
 */
export function installInstrument(channel: string): void {
  const MARKER = '__dshBrowserInstrument'
  const FLAG = '__dshBrowserInstrumentInstalled'
  const MAX_TEXT = 16_384
  if (Reflect.get(window, FLAG) === true) return
  Reflect.set(window, FLAG, true)

  const emit = (entry: unknown): void => {
    try {
      window.dispatchEvent(new CustomEvent(channel, { detail: { [MARKER]: true, entry } }))
    } catch {
      // Instrumentation must never break the page it observes.
    }
  }

  const stringify = (value: unknown): string => {
    if (typeof value === 'string') return value
    if (value instanceof Error) return value.stack ?? `${value.name}: ${value.message}`
    try {
      const json = JSON.stringify(value)
      return json === undefined ? String(value) : json
    } catch {
      try {
        return String(value)
      } catch {
        return '[unprintable]'
      }
    }
  }

  const emitConsole = (type: string, text: string, url: string, line?: number, column?: number): void => {
    try {
      emit({
        kind: 'console',
        type,
        text: text.slice(0, MAX_TEXT),
        url,
        ...(line === undefined ? {} : { line }),
        ...(column === undefined ? {} : { column }),
        timestamp: Date.now(),
      })
    } catch {
      // Reporting failure is not the page's problem.
    }
  }

  const consoleObject = window.console
  const consoleMethods = ['log', 'info', 'warn', 'error', 'debug'] as const
  for (const method of consoleMethods) {
    const original = consoleObject[method]
    if (typeof original !== 'function') continue
    const wrapped = function (this: unknown, ...args: unknown[]): void {
      try {
        emitConsole(method, args.map(stringify).join(' '), String(window.location.href))
      } catch {
        // Keep console output intact even when reporting throws.
      }
      return Reflect.apply(original, consoleObject, args)
    }
    Reflect.set(consoleObject, method, wrapped)
  }

  window.addEventListener('error', (event: ErrorEvent) => {
    const message = event.message !== '' ? event.message : (event.error instanceof Error ? event.error.message : 'Script error')
    emitConsole(
      'exception',
      `Uncaught ${message}`,
      event.filename !== '' ? event.filename : String(window.location.href),
      event.lineno,
      event.colno,
    )
  }, true)

  window.addEventListener('unhandledrejection', (event: PromiseRejectionEvent) => {
    const reason = event.reason
    const message = reason instanceof Error ? `${reason.name}: ${reason.message}` : stringify(reason)
    emitConsole('exception', `Uncaught (in promise) ${message}`, String(window.location.href))
  })

  const emitNetwork = (url: string, method: string, status: number, errorText?: string): void => {
    try {
      emit({
        kind: 'network',
        url,
        method,
        status,
        ...(errorText === undefined ? {} : { errorText: errorText.slice(0, 512) }),
        timestamp: Date.now(),
      })
    } catch {
      // Reporting failure is not the page's problem.
    }
  }

  const requestUrl = (input: unknown): string => {
    if (typeof input === 'string') return input
    if (input instanceof URL) return input.href
    if (typeof Request !== 'undefined' && input instanceof Request) return input.url
    return ''
  }

  const requestMethod = (input: unknown, init: unknown): string => {
    if (typeof init === 'object' && init !== null) {
      const method = Reflect.get(init, 'method')
      if (typeof method === 'string' && method !== '') return method.toUpperCase()
    }
    if (typeof Request !== 'undefined' && input instanceof Request && input.method !== '') return input.method.toUpperCase()
    return 'GET'
  }

  const originalFetch = window.fetch
  if (typeof originalFetch === 'function') {
    const wrappedFetch = async function (this: unknown, ...args: unknown[]): Promise<Response> {
      const url = requestUrl(args[0])
      const method = requestMethod(args[0], args[1])
      try {
        const response = await Reflect.apply(originalFetch, window, args) as Response
        emitNetwork(url, method, response.status)
        return response
      } catch (error: unknown) {
        emitNetwork(url, method, 0, error instanceof Error ? error.message : String(error))
        throw error
      }
    }
    Reflect.set(window, 'fetch', wrappedFetch)
  }

  const Xhr = window.XMLHttpRequest
  if (typeof Xhr === 'function' && Xhr.prototype !== undefined) {
    const prototype = Xhr.prototype
    const originalOpen = prototype.open
    const originalSend = prototype.send
    Reflect.set(prototype, 'open', function (this: XMLHttpRequest, method: string, url: string | URL, ...rest: unknown[]) {
      try {
        Reflect.set(this, '__dshRequest', { method: String(method).toUpperCase(), url: String(url) })
      } catch {
        // A frozen XHR instance still gets the original open call.
      }
      return Reflect.apply(originalOpen, this, [method, url, ...rest])
    })
    Reflect.set(prototype, 'send', function (this: XMLHttpRequest, ...args: unknown[]): void {
      try {
        const request = Reflect.get(this, '__dshRequest') as { method?: unknown; url?: unknown } | undefined
        const url = typeof request?.url === 'string' ? request.url : ''
        const method = typeof request?.method === 'string' ? request.method : 'GET'
        this.addEventListener('loadend', () => {
          try {
            const status = this.status
            emitNetwork(url, method, status, status === 0 ? 'request failed' : undefined)
          } catch {
            // A detached XHR cannot be inspected.
          }
        }, { once: true })
      } catch {
        // Keep the original send path intact.
      }
      return Reflect.apply(originalSend, this, args)
    })
  }
}

function isInstrumentConsoleEntry(value: unknown): value is InstrumentConsoleEntry {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  return record.kind === 'console'
    && typeof record.type === 'string'
    && typeof record.text === 'string'
    && typeof record.url === 'string'
    && typeof record.timestamp === 'number'
}

function isInstrumentNetworkEntry(value: unknown): value is InstrumentNetworkEntry {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  return record.kind === 'network'
    && typeof record.url === 'string'
    && typeof record.method === 'string'
    && typeof record.status === 'number'
    && typeof record.timestamp === 'number'
}

/**
 * Validate one page-posted entry before forwarding it to the background.
 * @param value - the event detail carrying the hook envelope.
 * @returns true when the value is a hook envelope with a known entry kind.
 */
export function isInstrumentMessage(value: unknown): value is InstrumentMessage {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  if (record[INSTRUMENT_MESSAGE_MARKER] !== true) return false
  const entry = record.entry
  return isInstrumentConsoleEntry(entry) || isInstrumentNetworkEntry(entry)
}

/**
 * Read the hook envelope from an event dispatched on the installed channel.
 *
 * Only an event whose type is the one-time channel name can carry a hook
 * message; a look-alike `message` event, a missing channel, or another custom
 * event type is rejected before its payload is inspected.
 * @param event - event delivered to the isolated world's window listener.
 * @param channel - channel name the background installed for this document.
 * @returns the validated envelope, or undefined for any other event.
 */
export function instrumentMessageFromEvent(event: Event, channel: string): InstrumentMessage | undefined {
  if (channel === '' || event.type !== channel) return undefined
  const detail = (event as CustomEvent<unknown>).detail
  return isInstrumentMessage(detail) ? detail : undefined
}

/**
 * Validate one entry received by the background worker.
 * @param value - the `entry` field of a forwarded message.
 * @returns true when the entry has the shape the buffer accepts.
 */
export function isInstrumentEntry(value: unknown): value is InstrumentEntry {
  return isInstrumentConsoleEntry(value) || isInstrumentNetworkEntry(value)
}
